/**
 * Helper to get a translated UI string, falling back to English.
 */
export function getUiTranslation(langCode, key, params = {}) {
  const lang = UI_TRANSLATIONS[langCode] || UI_TRANSLATIONS.en;
  let text = lang[key] || UI_TRANSLATIONS.en[key] || key;

  if (typeof text === 'string' && params) {
    Object.entries(params).forEach(([paramKey, val]) => {
      text = text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), val);
    });
  }

  return text;
}

/**
 * Format relative date localized for the given language.
 */
export function formatLocalizedRelativeDate(dateString, langCode = 'en') {
  if (!dateString) return '';
  const date = new Date(dateString);
  const now = new Date();
  const diffInSeconds = Math.floor((now - date) / 1000);

  if (diffInSeconds < 60) {
    return getUiTranslation(langCode, 'justNow');
  }
  const diffInMinutes = Math.floor(diffInSeconds / 60);
  if (diffInMinutes < 60) {
    if (diffInMinutes === 1) {
      return getUiTranslation(langCode, 'minuteAgo');
    }
    return getUiTranslation(langCode, 'minutesAgo', { n: diffInMinutes });
  }
  const diffInHours = Math.floor(diffInMinutes / 60);
  if (diffInHours < 24) {
    if (diffInHours === 1) {
      return getUiTranslation(langCode, 'hourAgo');
    }
    return getUiTranslation(langCode, 'hoursAgo', { n: diffInHours });
  }
  const diffInDays = Math.floor(diffInHours / 24);
  if (diffInDays === 1) {
    return getUiTranslation(langCode, 'yesterday');
  }
  if (diffInDays < 30) {
    return getUiTranslation(langCode, 'daysAgo', { n: diffInDays });
  }

  try {
    return date.toLocaleDateString(langCode === 'en' ? 'en-IN' : `${langCode}-IN`);
  } catch {
    return date.toLocaleDateString();
  }
}
